import assert from 'node:assert/strict';
import { createSellerCache, SELLER_CACHE_TTL_MS } from '../src/lib/seller-cache.ts';
let time = 0, calls = 0, finish;
const rows = [{ RTLRID: 'public-test', LATITUDE: 37, LONGITUDE: 127 }];
const cache = createSellerCache(() => { calls++; return new Promise(resolve => { finish = resolve; }); }, () => time);
const first = cache.load();
assert.equal(cache.load(), first, 'Concurrent readers must share one request');
assert.equal(calls, 1);
finish(rows);
assert.equal(await first, rows);
time = SELLER_CACHE_TTL_MS - 1;
assert.equal(await cache.load(), rows);
assert.equal(calls, 1, 'Fresh data must not refetch');
time = SELLER_CACHE_TTL_MS;
const refresh = cache.load();
assert.equal(cache.load(), refresh);
assert.equal(calls, 2, 'Expired data must refetch once');
finish(rows);
await refresh;
let attempts = 0;
const retry = createSellerCache(async () => { if (++attempts === 1) throw Error('upstream failure'); return rows; });
await assert.rejects(retry.load());
assert.equal(await retry.load(), rows);
assert.equal(attempts, 2, 'Errors must not poison the cache');
let malformedAttempts = 0;
const malformed = createSellerCache(async () => ++malformedAttempts === 1 ? {} : rows);
await assert.rejects(malformed.load());
assert.equal(await malformed.load(), rows);
console.log('Seller cache: deduplication, one-hour TTL, error and malformed-response recovery PASS');
